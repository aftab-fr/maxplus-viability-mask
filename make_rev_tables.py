def ablation():
    df = pd.read_csv(RES / "rev_ablation.csv")
    df["group"] = df.run.str.replace(r"_s\d+$", "", regex=True)
    o = df[df.run == "oracle"].groupby(["D", "year"]).cost.mean()
    lab = {"penalty_p50": ("PPO+penalty, 50\\,\\EUR", "PFifty"),
           "penalty_p150": ("PPO+penalty, 150\\,\\EUR", "POneFifty"),
           "penalty": ("PPO+penalty, 500\\,\\EUR", "PFiveHundred"),
           "penalty_p2000": ("PPO+penalty, 2\\,000\\,\\EUR", "PTwoThousand"),
           "penalty_noslack": ("PPO+penalty, no slack", "PNoSlack"),
           "shield_noslack": ("PPO+shield, no slack", "SNoSlack")}
    if (RES / "rev_cfga.csv").exists():
        cf = pd.read_csv(RES / "rev_cfga.csv")
        cf["group"] = cf.run.str.replace(r"_s\d+$", "", regex=True)
        df = pd.concat([df, cf[cf.run.str.contains("cfgA")]])
        lab["penalty_cfgA"] = ("PPO+penalty, own tuning (A)", "PCfgA")
        lab["shield_cfgA"] = ("PPO+shield, own tuning (A)", "SCfgA")
    sh = pd.read_csv(RES / "deadline_shift.csv")
    rows = [r"\begin{tabular}{lrrrrrr}", r"\toprule",
            r" & & \multicolumn{2}{c}{$D=23$\,h} & \multicolumn{3}{c}{$D=19$\,h (not retrained)} \\",
            r"\cmidrule(lr){3-4}\cmidrule(lr){5-7}",
            r"Agent & seeds & gap (\%) & late & gap (\%) & late & overrides \\", r"\midrule"]
    for gname, (txt, k) in lab.items():
        r = []
        for D in (23.0, 19.0):
            g = df[(df.D == D) & (df.group == gname)]
            if g.empty:
                r.append(None)
                continue
            gap = (100 * (g.groupby("year").cost.mean() / o.loc[D] - 1)).mean()
            r.append((gap, int((g.viol > 0).sum()), int((g.safety > 0).sum()), len(g),
                      g.run.nunique()))
        if r[0] is None:
            continue
        d(f"Ab{k}GapN", f1(r[0][0]))
        d(f"Ab{k}LateN", str(r[0][1]))
        d(f"Ab{k}LateNPct", f1(100 * r[0][1] / r[0][3]))
        d(f"Ab{k}GapT", f1(r[1][0]))
        d(f"Ab{k}LateT", str(r[1][1]))
        d(f"Ab{k}LateTPct", f1(100 * r[1][1] / r[1][3]))
        d(f"Ab{k}SafeT", str(r[1][2]))
        rows.append(f"{txt} & {r[0][4]} & {r[0][0]:.1f} & {r[0][1]} & {r[1][0]:.1f} & {r[1][1]} & {r[1][2]} \\\\")
    # masked agent (10 seeds) from main evaluation + deadline shift
    dc = pd.read_csv(RES / "daily_costs.csv")
    g = dc[(dc.sigma == 0.15) & dc.year.isin([2020, 2023])]
    orc = g[g.method == O].groupby("year").cost.mean()
    gm = (100 * (g[g.method == M].groupby("year").cost.mean() / orc - 1)).mean()
    s19 = sh[(sh.deadline == 19.0)]
    o19 = s19[s19.method == O].groupby("year").cost.mean()
    hm = s19[s19.method == M]
    gm19 = (100 * (hm.groupby("year").cost.mean() / o19 - 1)).mean()
    rows.append(r"\midrule")
    rows.append(f"MaskablePPO+mask (ours) & {hm.seed.nunique()} & {gm:.1f} & 0 & {gm19:.1f} & "
                f"{int((hm.violations > 0).sum())} & 0 \\\\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "tab_ablation_ext.tex").write_text("\n".join(rows) + "\n")
    # 10-seed deadline shift macros
    for D, dk in ((21.0, "TwentyOne"), (19.0, "Nineteen")):
        s = sh[sh.deadline == D]
        oo = s[s.method == O].groupby("year").cost.mean()
        for m, k in ((M, "Mask"), (P, "Pen"), (S, "Shield"), (E, "EMPC")):
            h = s[s.method == m]
            d(f"Sh{k}D{dk}Late", str(int((h.violations > 0).sum())))
            d(f"Sh{k}D{dk}N", str(len(h)))
            d(f"Sh{k}D{dk}LatePct", f1(100 * (h.violations > 0).mean()))
            d(f"Sh{k}D{dk}Safe", str(int((h.safety_interventions > 0).sum())))
            d(f"Sh{k}D{dk}Gap", f1((100 * (h.groupby("year").cost.mean() / oo - 1)).mean()))


