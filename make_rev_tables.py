"""
LaTeX macros and tables for the experiments added in the revision, so that
no number in the revised manuscript or the response letter is typed by hand.

Reads results/*.csv|json produced by: stats_rev.py (via daily_costs.csv),
rev_eval_extra.py, forecast_rev.py, costmodel_rev.py, robust_ext.py,
robustness.py, policy_agnostic.py, explain_audit.py, scale_run.py,
deadline_shift (evaluate.py --shift).

Output: generated/rev_macros.tex and rineng/generated/tab_*.tex
        generated/response_numbers.tex (same macros, for the letter)
"""

import json
from pathlib import Path

import numpy as np
import pandas as pd

from stats_rev import compare

RES = Path("results")
OUT = Path("generated")
M = "MaskablePPO + max-plus mask (proposed)"
P = "PPO + deadline penalty"
S = "PPO + post-hoc shield"
E = "Max-plus EMPC (forecast)"
L = "Latest start (11-13 h)"
DS = "Day shift (08-10 h)"
B = "Best block (forecast)"
O = "Oracle (perfect information)"
SHORT = {M: "MaskablePPO+mask (ours)", P: "PPO+penalty", S: "PPO+shield", E: "Max-plus EMPC",
         L: "Latest start", DS: "Day shift", B: "Best block"}

mac = ["% auto-generated by make_rev_tables.py -- do not edit"]


def d(name, val):
    mac.append(rf"\newcommand{{\{name}}}{{{val}}}")


def f1(x):
    return f"{x:.1f}"


def f2(x):
    return f"{x:.2f}"


def ci(lo, hi, k=2):
    return f"[{lo:.{k}f}, {hi:.{k}f}]"


# --------------------------------------------------------------- statistics
def stats_table():
    df = pd.read_csv(RES / "daily_costs.csv")
    rows = [r"\begin{tabular}{llrrrrr}", r"\toprule",
            r"Year & Comparison (A vs B) & $\Delta$ (\EUR/day) & 95\% CI & $\Delta$ (\%) & $d_z$ & $r_{rb}$ \\",
            r"\midrule"]
    pairs = [(M, L), (M, DS), (M, B), (M, E), (M, P), (M, S), (P, S)]
    out = {}
    lagac = []
    for y in (2020, 2023):
        g = df[(df.year == y) & (df.sigma == 0.15)]
        for a, b in pairs:
            r = compare(g, a, b)
            out[(y, a, b)] = r
            lagac.append(r["lag1_ac"])
            rows.append(f"{y} & {SHORT[a]} vs {SHORT[b]} & {r['delta']:+.2f} & {ci(r['ci_lo'], r['ci_hi'])} & "
                        f"{r['rel_pct']:+.1f} & {r['cohen_dz']:+.2f} & {r['r_rb']:+.2f} \\\\")
        rows.append(r"\midrule" if y == 2020 else r"\bottomrule")
    rows.append(r"\end{tabular}")
    (OUT / "tab_stats.tex").write_text("\n".join(rows) + "\n")
    yk = {2020: "C", 2023: "D"}
    nm = {L: "Late", DS: "Day", B: "Block", E: "EMPC", P: "Pen", S: "Shield"}
    for (y, a, b), r in out.items():
        if a != M:
            continue
        k = f"St{nm[b]}{yk[y]}"
        d(k + "D", f2(r["delta"]))
        d(k + "Lo", f2(r["ci_lo"]))
        d(k + "Hi", f2(r["ci_hi"]))
        d(k + "Rel", f1(r["rel_pct"]))
        d(k + "Sav", f1(-r["rel_pct"]))
        d(k + "RelLo", f1(r["rel_ci_lo"]))
        d(k + "RelHi", f1(r["rel_ci_hi"]))
        d(k + "Dz", f2(r["cohen_dz"]))
    for nmk in ("Block", "Day", "Late"):
        v = [-out[(y, M, b)]["rel_pct"] for y in (2020, 2023) for b in (B, DS, L) if nm[b] == nmk]
        d(f"St{nmk}SavMin", f"{min(v):.0f}")
        d(f"St{nmk}SavMax", f"{max(v):.0f}")
    d("StLagMin", f2(min(lagac)))
    d("StLagMax", f2(max(lagac)))
    # seed ranges (gap to oracle, mean of test years)
    g = df[(df.sigma == 0.15) & df.year.isin([2020, 2023])]
    orc = g[g.method == O].groupby("year").cost.mean()
    for m, k in ((M, "Mask"), (P, "Pen"), (S, "Shield")):
        per = g[g.method == m].groupby(["seed", "year"]).cost.mean().unstack()
        gap = (100 * (per / orc - 1)).mean(1)
        d(f"SeedMin{k}", f1(gap.min()))
        d(f"SeedMax{k}", f1(gap.max()))
        d(f"NSeeds{k}", str(len(gap)))
        d(f"LateDaysNom{k}", str(int((g[g.method == m].violations > 0).sum())))


