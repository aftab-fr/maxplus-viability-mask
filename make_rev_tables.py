def tuning():
    df = pd.read_csv(RES / "rev_tuning.csv")
    o = df[df.run == "oracle"].groupby("year").cost.mean()
    g = df[df.run.str.contains("tune")].groupby(["run", "year"]).cost.mean().unstack()
    gap = 100 * (g / o - 1)
    cfg = {"A": r"$\eta=3\times10^{-4}$, ent.\ 0.01, [64,64]",
           "B": r"$\eta=3\times10^{-4}$, ent.\ 0.001, [128,128]",
           "C": r"$\eta=10^{-4}$, ent.\ 0.001, [128,128]",
           "D": r"$\eta=3\times10^{-4}$, ent.\ 0.003, [256,256]"}
    rows = [r"\begin{tabular}{llrrrrrr}", r"\toprule",
            r" & & \multicolumn{2}{c}{MaskablePPO+mask} & \multicolumn{2}{c}{PPO+penalty} & \multicolumn{2}{c}{PPO+shield} \\",
            r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}",
            r"Config. & Hyperparameters & train & valid. & train & valid. & train & valid. \\", r"\midrule"]
    best = {}
    for v in ("mask", "penalty", "shield"):
        sub = gap[gap.index.str.startswith(v + "_")]
        tr = sub[[2018, 2019]].mean(1)
        best[v] = (tr.idxmin()[-5], sub[2021].idxmin()[-5])
    for c in "ABCD":
        cells = []
        for v in ("mask", "penalty", "shield"):
            r = gap.loc[f"{v}_tune{c}_s90"]
            tr, va = r[[2018, 2019]].mean(), r[2021]
            bt = r"\textbf{%.1f}" % tr if best[v][0] == c else f"{tr:.1f}"
            bv = r"\textbf{%.1f}" % va if best[v][1] == c else f"{va:.1f}"
            cells += [bt, bv]
        rows.append(f"{c} & {cfg[c]} & " + " & ".join(cells) + r" \\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "tab_tuning.tex").write_text("\n".join(rows) + "\n")


