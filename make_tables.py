"""
Turn results/*.json and runs/*/episodes.csv into LaTeX macros and tables
for the manuscript, so that no number is typed by hand.

Output: jcaes/generated/results_macros.tex
        jcaes/generated/table_costs.tex
        jcaes/generated/table_ablation.tex
"""

import json
from pathlib import Path

import numpy as np
import pandas as pd

from figures import (M_BLOCK, M_DAY, M_EMPC, M_LATE, M_MASK, M_OR, M_PEN,
                     M_SHIELD, SHORT)

RES = Path("results")
OUT = Path("generated")
OUT.mkdir(parents=True, exist_ok=True)

KEY = {M_MASK: "Mask", M_SHIELD: "Shield", M_PEN: "Penalty", M_DAY: "Day",
       M_LATE: "Late", M_BLOCK: "Block", M_EMPC: "EMPC", M_OR: "Oracle"}
YK = {2018: "A", 2019: "B", 2020: "C", 2023: "D"}
SK = {0.0: "Z", 0.15: "", 0.3: "H"}
ORDER = [M_DAY, M_LATE, M_BLOCK, M_PEN, M_SHIELD, M_MASK, M_EMPC, M_OR]


def fmt_p(p):
    if p is None or np.isnan(p):
        return "--"
    return r"<\!0.001" if p < 1e-3 else f"{p:.3f}"


def main():
    S = json.loads((RES / "summary.json").read_text())
    T = json.loads((RES / "timing.json").read_text())
    E = json.loads((RES / "explain_stats.json").read_text())
    mac = ["% auto-generated by make_tables.py -- do not edit"]
    d = lambda name, val: mac.append(rf"\newcommand{{\{name}}}{{{val}}}")

    for y, yk in YK.items():
        for s, sk in SK.items():
            tab = S[f"{y}_sigma{s}"]
            for m, mk in KEY.items():
                e = tab[m]
                d(f"Cost{mk}{yk}{sk}", f"{e['mean']:.2f}")
                d(f"Gap{mk}{yk}{sk}", f"{e['gap_to_oracle_pct']:.1f}")
                d(f"Sav{mk}{yk}{sk}", f"{e['saving_vs_latest_pct']:.1f}")
                d(f"Std{mk}{yk}{sk}", f"{e['seed_std']:.2f}")
                d(f"Viol{mk}{yk}{sk}", str(e["violations_days"]))
                if "wilcoxon_p_vs_empc" in e:
                    d(f"PEmpc{mk}{yk}{sk}", fmt_p(e["wilcoxon_p_vs_empc"]))
                    d(f"DEmpc{mk}{yk}{sk}", f"{e['mean_diff_vs_empc']:.2f}")
                if "wilcoxon_p_vs_latest" in e:
                    d(f"PLate{mk}{yk}{sk}", fmt_p(e["wilcoxon_p_vs_latest"]))

    # averages over the two held-out years (sigma = 0.15)
    for m, mk in KEY.items():
        g = np.mean([S[f"{y}_sigma0.15"][m]["gap_to_oracle_pct"] for y in (2020, 2023)])
        v = np.mean([S[f"{y}_sigma0.15"][m]["saving_vs_latest_pct"] for y in (2020, 2023)])
        d(f"GapTest{mk}", f"{g:.1f}")
        d(f"SavTest{mk}", f"{v:.1f}")

    d("TimeMask", f"{T['mask_ms']:.3f}")
    d("TimePolicy", f"{T['policy_ms']:.3f}")
    d("TimeEMPC", f"{T['empc_ms']:.3f}")
    d("NFeasible", str(T["n_feasible_schedules"]))
    d("TimeEnum", f"{T['enumeration_s']:.2f}")

    for key, st in E.items():
        y, m = key.split("|")
        mk, yk = KEY[m], YK[int(y)]
        d(f"ExForced{mk}{yk}", f"{st['forced_pct']:.2f}")
        d(f"ExSlack{mk}{yk}", f"{st['mean_slack_h']:.1f}")
        d(f"ExCons{mk}{yk}", f"{st['locally_consistent_pct']:.1f}")
        d(f"ExPV{mk}{yk}", f"{st['mean_pv_share_pct']:.1f}")
        d(f"ExPrev{mk}{yk}", f"{st['oven_driven_by_previous_job_pct']:.1f}")
        d(f"ExN{mk}{yk}", str(st["releases"]))

    # training-time infeasibility (deadline-relevant events only)
    col = {"mask": None, "shield": "safety_interventions", "penalty": "violations"}
    abl = {}
    for v in ("mask", "shield", "penalty"):
        ep = [pd.read_csv(p / "episodes.csv") for p in
              sorted(Path("runs").glob(f"{v}_s[0-9]"))]
        ev = [e[col[v]] if col[v] else 0 * e.cost for e in ep]
        tot = [float(x.sum()) for x in ev]
        last = [float(e.timestep[x > 0].max()) / 1e6 if (x > 0).any() else 0.0
                for x, e in zip(ev, ep)]
        abl[v] = (min(tot), max(tot), min(last), max(last))
        k = {"mask": "Mask", "shield": "Shield", "penalty": "Penalty"}[v]
        d(f"TrMin{k}", f"{min(tot):.0f}")
        d(f"TrMax{k}", f"{max(tot):.0f}")
        d(f"TrLastMin{k}", f"{min(last):.1f}")
        d(f"TrLastMax{k}", f"{max(last):.1f}")

    # deadline-shift and processing-delay macros/tables: see make_rev_tables.py
    SH = json.loads((RES / "deadline_shift.json").read_text())

    # ---- scalability
    SC = json.loads((RES / "scalability.json").read_text())
    rows = [r"\begin{tabular}{rrrrrrr}", r"\toprule",
            r"Epoch & Jobs & Candidates & Feasible & Enumeration & EMPC solve & Mask \\",
            r"(min) & $N$ & $\binom{T}{N}$ & schedules & (s) & (ms) & (ms) \\", r"\midrule"]
    def big(v):
        return f"{v:,}".replace(",", "\\,") if v < 1e7 else f"${v / 10 ** int(np.log10(v)):.1f}\\times10^{{{int(np.log10(v))}}}$"
    for e in SC:
        if "feasible" in e:
            rows.append(f"{int(e['dt_h'] * 60)} & {e['n_jobs']} & {big(e['candidates'])} & {big(e['feasible'])} & "
                        f"{e['enumeration_s']:.2f} & {e['empc_solve_ms']:.1f} & {e['mask_ms']:.3f} \\\\")
        else:
            rows.append(f"{int(e['dt_h'] * 60)} & {e['n_jobs']} & {big(e['candidates'])} & -- & -- & -- & {e['mask_ms']:.3f} \\\\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "table_scal.tex").write_text("\n".join(rows) + "\n")
    big_e = [e for e in SC if "feasible" in e]
    last = max(big_e, key=lambda e: e["feasible"])
    d("ScMaxFeasible", big(last["feasible"]))
    d("ScMaxSolve", f"{last['empc_solve_ms']:.0f}")
    d("ScMaxEpoch", f"{int(last['dt_h'] * 60)}")
    d("ScMaxJobs", str(last["n_jobs"]))
    d("ScMaskMax", f"{max(e['mask_ms'] for e in SC):.2f}")

    # Gantt / explanation day
    from figures import pick_gantt_day
    df = pd.read_csv(RES / "daily_costs.csv")
    gd = pick_gantt_day(df)
    g = df[(df.year == 2023) & (df.sigma == 0.15) & (df.date == gd)]
    d("GanttDate", gd)
    d("GanttLate", f"{g[g.method == M_LATE].cost.iloc[0]:.1f}")
    d("GanttOracle", f"{g[g.method == M_OR].cost.iloc[0]:.1f}")
    d("GanttMask", f"{g[(g.method == M_MASK) & (g.seed == 0)].cost.iloc[0]:.1f}")
    d("GanttMaskSched", g[(g.method == M_MASK) & (g.seed == 0)].schedule.iloc[0].replace(" ", ", "))
    d("GanttOracleSched", g[g.method == M_OR].schedule.iloc[0].replace(" ", ", "))
    ex = (RES / "explanation_example.txt").read_text().splitlines()[1:]
    (OUT / "explanation_example.txt").write_text("\n".join(ex) + "\n")
    (OUT / "results_macros.tex").write_text("\n".join(mac) + "\n")

    # ---- Table: daily cost and gap per year (sigma = 0.15)
    rows = [r"\begin{tabular}{l" + "rr" * 4 + "}", r"\toprule",
            r" & \multicolumn{2}{c}{2018 (train)} & \multicolumn{2}{c}{2019 (train)}"
            r" & \multicolumn{2}{c}{2020 (test)} & \multicolumn{2}{c}{2023 (test)} \\",
            r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}",
            r"Method & Cost & Gap & Cost & Gap & Cost & Gap & Cost & Gap \\",
            r"\midrule"]
    for m in ORDER:
        cells = []
        for y in YK:
            e = S[f"{y}_sigma0.15"][m]
            c = f"{e['mean']:.1f}"
            if e["n_seeds"] > 1:
                c += rf"$\pm${e['seed_std']:.1f}"
            g = "--" if m == M_OR else f"{e['gap_to_oracle_pct']:.1f}"
            cells += [c, g]
        name = SHORT[m] + (" (ours)" if m == M_MASK else "")
        if m == M_MASK:
            cells = [rf"\textbf{{{c}}}" for c in cells]
            name = rf"\textbf{{{name}}}"
        if m == M_EMPC:
            rows.append(r"\midrule")
        rows.append(name + " & " + " & ".join(cells) + r" \\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "table_costs.tex").write_text("\n".join(rows) + "\n")

    # ---- Table: feasibility ablation (nominal D=23 and shifted deadlines)
    rows = [r"\begin{tabular}{lrrrrrrr}", r"\toprule",
            r" & \multicolumn{2}{c}{Training (per run)} & \multicolumn{2}{c}{Test, $D=23$\,h}"
            r" & \multicolumn{3}{c}{Test, $D=19$\,h (not retrained)} \\",
            r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-8}",
            r"Variant & events & last event & events & gap & events & late jobs & gap \\",
            r"\midrule"]
    for v, m in (("penalty", M_PEN), ("shield", M_SHIELD), ("mask", M_MASK)):
        tmin, tmax, lmin, lmax = abl[v]
        tr = f"{tmin:.0f}--{tmax:.0f}" if tmax > 0 else "0"
        la = f"{lmin:.1f}--{lmax:.1f}\\,M" if tmax > 0 else "--"
        ev = sum(S[f"{y}_sigma0.15"][m]["violations_days"] +
                 S[f"{y}_sigma0.15"][m]["safety_days"] for y in (2020, 2023))
        gap = np.mean([S[f"{y}_sigma0.15"][m]["gap_to_oracle_pct"] for y in (2020, 2023)])
        e19 = SH["D19"][m]
        ev19 = e19["violation_seed_days"] + e19["safety_seed_days"]
        name = SHORT[m] + (" (ours)" if v == "mask" else "")
        rows.append(f"{name} & {tr} & {la} & {ev} & "
                    f"{gap:.1f}\\% & {ev19} & {e19['late_jobs']} & "
                    f"{e19['gap_to_oracle_pct']:.1f}\\% \\\\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "table_ablation.tex").write_text("\n".join(rows) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
