"""
Verification of the viability mask beyond the case-study assumptions
(revision: R3-Methods "identical jobs, common deadline, one release per
epoch"; R2-m1 role of T + sum(p) > D).

Generalised setting:
  * job-dependent processing times p(k) (time-varying max-plus matrices
    A(k), B(k)),
  * job-dependent deadlines D_k (jobs are released in a fixed order),
  * up to c releases per epoch (action a_t in {0, ..., c}).

Generalised viability: V(x, tau, k) holds iff releasing the remaining jobs
k, k+1, ..., N-1 as early as admissible (c per epoch from tau on) makes
every one of them meet its own deadline. Mask: a_t = j is admissible iff
after releasing j jobs at t the state is viable from t+1.

For random instances the set of release sequences generated by DFS under
the mask is compared with the brute-force set of feasible sequences, and
non-emptiness of the mask along every DFS branch is checked.
"""

import itertools

import numpy as np

from maxplus import SerialLine, EPS


def simulate(x, rel, jobs, lines):
    """Completion vectors after releasing jobs `jobs` at times `rel`."""
    comps = []
    for k, u in zip(jobs, rel):
        x = lines[k].next_state(x, float(u))
        comps.append(x[-1])
    return x, comps


def earliest(tau, m, c):
    return [tau + j // c for j in range(m)]


HORIZON_IN_V = True


def viable(x, tau, k, N, lines, D, c, T=None):
    if k >= N:
        return True
    rel = earliest(tau, N - k, c)
    if HORIZON_IN_V and T is not None and rel[-1] > T - 1:
        return False            # remaining jobs cannot all be released by T-1
    _, comps = simulate(x, rel, range(k, N), lines)
    return all(y <= D[j] + 1e-9 for y, j in zip(comps, range(k, N)))


def mask(x, t, k, N, lines, D, c, T):
    adm = []
    for j in range(0, min(c, N - k) + 1):
        if t >= T and j == 0 and k < N:
            continue
        x2, comps = simulate(x, [t] * j, range(k, k + j), lines)
        ok = all(y <= D[i] + 1e-9 for y, i in zip(comps, range(k, k + j)))
        if ok and viable(x2, t + 1, k + j, N, lines, D, c, T):
            adm.append(j)
    return adm


def dfs(T, N, lines, D, c):
    out, empty = set(), 0
    stack = [(0, 0, np.full(lines[0].n, EPS), ())]
    while stack:
        t, k, x, rel = stack.pop()
        if k == N:
            out.add(rel)
            continue
        if t >= T:
            empty += 1          # would mean jobs left at the horizon
            continue
        adm = mask(x, t, k, N, lines, D, c, T)
        if not adm:
            empty += 1
            continue
        for j in adm:
            x2, _ = simulate(x, [t] * j, range(k, k + j), lines)
            stack.append((t + 1, k + j, x2, rel + (t,) * j))
    return out, empty


def brute(T, N, lines, D, c):
    out = set()
    for rel in itertools.combinations_with_replacement(range(T), N):
        if max(rel.count(u) for u in set(rel)) > c:
            continue
        _, comps = simulate(np.full(lines[0].n, EPS), rel, range(N), lines)
        if all(y <= D[k] + 1e-9 for k, y in enumerate(comps)):
            out.add(rel)
    return out


def main(n_inst=300, seed=7):
    rng = np.random.default_rng(seed)
    stats = dict(instances=0, nonempty_feasible=0, mismatches=0, empty_masks=0,
                 schedules=0)
    for _ in range(n_inst):
        n = int(rng.integers(2, 5))                 # machines
        N = int(rng.integers(2, 5))                 # jobs
        T = int(rng.integers(8, 14))                # epochs
        c = int(rng.integers(1, 3))                 # releases per epoch
        lines = [SerialLine(rng.integers(1, 4, n).astype(float)) for _ in range(N)]
        D = np.sort(rng.uniform(4, T + 6, N))       # individual deadlines
        if not rng.integers(0, 3):                  # some common-deadline cases
            D[:] = D[-1]
        # Theorem condition: no job can wait beyond the horizon and still be
        # on time (T + p_min > D_k), as in T + sum(p) > D
        bf = brute(T, N, lines, D, c)
        dm, emp = dfs(T, N, lines, D, c)
        stats["instances"] += 1
        stats["schedules"] += len(bf)
        if not viable(np.full(n, EPS), 0, 0, N, lines, D, c, T):
            assert not bf, "V(eps,0,N) false but feasible schedules exist"
            continue
        stats["nonempty_feasible"] += 1
        stats["empty_masks"] += emp
        if bf != dm:
            stats["mismatches"] += 1
    print(stats)
    return stats


if __name__ == "__main__":
    import sys
    HORIZON_IN_V = "--no-horizon" not in sys.argv
    print("horizon constraint in V:", HORIZON_IN_V)
    main()
